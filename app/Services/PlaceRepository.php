    /**
     * Categories for Outside Campus Tour - Computed dynamically
     */
    public static function getOutsideCategories(): array
    {
        $places = self::getOutsidePlaces();
        $counts = [];
        foreach ($places as $p) {
            $cat = $p['category_id'] ?? 'other';
            $counts[$cat] = ($counts[$cat] ?? 0) + 1;
        }

        $definitions = [
            ['id' => 'all', 'name' => 'All Nearby', 'icon' => 'layout-grid', 'count' => count($places)],
            ['id' => 'food', 'name' => 'Food & Dhabas', 'icon' => 'utensils', 'count' => $counts['food'] ?? 0],
            ['id' => 'restaurants', 'name' => 'Restaurants', 'icon' => 'store', 'count' => $counts['restaurants'] ?? 0],
            ['id' => 'cafes', 'name' => 'Cafes', 'icon' => 'coffee', 'count' => $counts['cafes'] ?? 0],
            ['id' => 'grocery', 'name' => 'Grocery & Markets', 'icon' => 'shopping-bag', 'count' => $counts['grocery'] ?? 0],
            ['id' => 'transportation', 'name' => 'Transit & Stations', 'icon' => 'bus', 'count' => $counts['transportation'] ?? 0],
            ['id' => 'services', 'name' => 'Pharmacies & Services', 'icon' => 'activity', 'count' => $counts['services'] ?? 0],
        ];

        return array_values(array_filter($definitions, fn($c) => $c['count'] > 0));
    }

    /**
     * General categories for browsing / search
     */
    public static function getCategories(): array
    {
        $all = self::getAllPlaces();
        $inside = self::getInsidePlaces();

        return [
            ['id' => 'all', 'name' => 'All Places', 'icon' => 'layout-grid', 'count' => count($all)],
            ['id' => 'campus-facilities', 'name' => 'Campus Facilities', 'icon' => 'landmark', 'count' => count($inside)],
            ['id' => 'food-drinks', 'name' => 'Food & Restaurants', 'icon' => 'utensils', 'count' => count(array_filter($all, fn($p) => in_array($p['category_id'], ['food', 'restaurants', 'cafes'])))],
            ['id' => 'cafes', 'name' => 'Cafes & Study', 'icon' => 'coffee', 'count' => count(array_filter($all, fn($p) => $p['category_id'] === 'cafes'))],
            ['id' => 'grocery', 'name' => 'Daily Needs', 'icon' => 'shopping-bag', 'count' => count(array_filter($all, fn($p) => $p['category_id'] === 'grocery'))],
            ['id' => 'transportation', 'name' => 'Transit & Rail', 'icon' => 'bus', 'count' => count(array_filter($all, fn($p) => $p['category_id'] === 'transportation'))],
        ];
    }

