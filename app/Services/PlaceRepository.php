            ['id' => 'auditorium', 'name' => 'Auditorium', 'icon' => 'ticket', 'count' => $counts['auditorium'] ?? 0],
            ['id' => 'sports', 'name' => 'Sports & Gymkhana', 'icon' => 'trophy', 'count' => $counts['sports'] ?? 0],
            ['id' => 'food', 'name' => 'Dining & Cafes', 'icon' => 'utensils', 'count' => $counts['food'] ?? 0],
            ['id' => 'administration', 'name' => 'Administration', 'icon' => 'briefcase', 'count' => $counts['administration'] ?? 0],
            ['id' => 'healthcare', 'name' => 'Health & Medical', 'icon' => 'activity', 'count' => $counts['healthcare'] ?? 0],
